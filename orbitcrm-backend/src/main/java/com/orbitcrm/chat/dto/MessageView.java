package com.orbitcrm.chat.dto;

import java.time.Instant;
import java.util.UUID;

/**
 * One chat message as returned by the API and pushed in {@code message.created} / {@code message.updated} stream
 * events.
 *
 * <p>Purpose: the single message shape for history, sending, editing and live delivery. The client matches its
 * optimistic message by {@code clientId} and every later update by {@code id}. A deleted message keeps its place
 * in the conversation but has no body.
 *
 * @author Abhay
 * @param id             message id (time-ordered)
 * @param conversationId conversation the message belongs to
 * @param senderId       author
 * @param body           text, or {@code null} once deleted
 * @param clientId       id generated by the sender's app, used to make sending idempotent
 * @param createdAt      when the server stored it (database clock)
 * @param editedAt       last edit, or {@code null}
 * @param deleted        true once the author deleted it
 */
public record MessageView(UUID id, UUID conversationId, UUID senderId, String body, String clientId,
                          Instant createdAt, Instant editedAt, boolean deleted) {
}
