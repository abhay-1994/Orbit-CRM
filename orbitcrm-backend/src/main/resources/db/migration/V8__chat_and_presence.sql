-- Phase 8: in-app chat (direct messages) and Teams-style presence.

-- ---------------------------------------------------------------------------
-- Conversations: one row per chat. Direct chats carry a key built from the two user ids in sorted
-- order, so each pair of people has exactly one conversation.
-- ---------------------------------------------------------------------------
CREATE TABLE chat_conversations (
    id              uuid PRIMARY KEY,
    tenant_id       uuid        NOT NULL REFERENCES tenants (id),
    kind            varchar(10) NOT NULL DEFAULT 'DIRECT',
    direct_key      varchar(80),
    created_by      uuid        NOT NULL,
    created_at      timestamptz NOT NULL,
    last_message_at timestamptz,
    CONSTRAINT uq_chat_conversations_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_chat_conversations_direct UNIQUE (tenant_id, direct_key),
    CONSTRAINT ck_chat_conversations_kind CHECK (kind IN ('DIRECT')),
    CONSTRAINT fk_chat_conversations_creator FOREIGN KEY (tenant_id, created_by) REFERENCES users (tenant_id, id)
);

CREATE TABLE chat_participants (
    tenant_id       uuid        NOT NULL,
    conversation_id uuid        NOT NULL,
    user_id         uuid        NOT NULL,
    joined_at       timestamptz NOT NULL,
    last_read_at    timestamptz,
    PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT fk_chat_participants_conversation FOREIGN KEY (tenant_id, conversation_id)
        REFERENCES chat_conversations (tenant_id, id),
    CONSTRAINT fk_chat_participants_user FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id)
);
CREATE INDEX ix_chat_participants_user ON chat_participants (tenant_id, user_id);

-- ---------------------------------------------------------------------------
-- Messages. client_id is generated by the sender's app: a retried send with the same id returns the
-- original message instead of creating a duplicate.
-- ---------------------------------------------------------------------------
CREATE TABLE chat_messages (
    id              uuid PRIMARY KEY,
    tenant_id       uuid          NOT NULL,
    conversation_id uuid          NOT NULL,
    sender_id       uuid          NOT NULL,
    client_id       varchar(64)   NOT NULL,
    body            varchar(4000) NOT NULL,
    created_at      timestamptz   NOT NULL,
    edited_at       timestamptz,
    deleted_at      timestamptz,
    CONSTRAINT fk_chat_messages_conversation FOREIGN KEY (tenant_id, conversation_id)
        REFERENCES chat_conversations (tenant_id, id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (tenant_id, sender_id) REFERENCES users (tenant_id, id),
    CONSTRAINT uq_chat_messages_client UNIQUE (tenant_id, sender_id, client_id)
);
CREATE INDEX ix_chat_messages_history ON chat_messages (tenant_id, conversation_id, created_at DESC, id DESC);

-- ---------------------------------------------------------------------------
-- Presence. user_presence holds the status a person chose (no row or NULL = automatic);
-- chat_connections has one row per open live stream (browser tab), so a person is online while any
-- of their connections has a recent heartbeat - on any server instance. idle is reported by the
-- tab after a few minutes without keyboard or mouse input.
-- ---------------------------------------------------------------------------
CREATE TABLE user_presence (
    tenant_id     uuid        NOT NULL,
    user_id       uuid        NOT NULL,
    manual_status varchar(20),
    updated_at    timestamptz NOT NULL,
    PRIMARY KEY (tenant_id, user_id),
    CONSTRAINT fk_user_presence_user FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id),
    CONSTRAINT ck_user_presence_status
        CHECK (manual_status IN ('BUSY', 'DO_NOT_DISTURB', 'BE_RIGHT_BACK', 'AWAY', 'OFFLINE'))
);

CREATE TABLE chat_connections (
    id             uuid PRIMARY KEY,
    tenant_id      uuid        NOT NULL,
    user_id        uuid        NOT NULL,
    instance_id    varchar(64) NOT NULL,
    idle           boolean     NOT NULL DEFAULT false,
    connected_at   timestamptz NOT NULL,
    last_heartbeat timestamptz NOT NULL,
    CONSTRAINT fk_chat_connections_user FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id)
);
CREATE INDEX ix_chat_connections_user ON chat_connections (tenant_id, user_id);
-- Cross-tenant sweep of connections whose server stopped sending heartbeats.
CREATE INDEX ix_chat_connections_heartbeat ON chat_connections (last_heartbeat);

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['chat_conversations', 'chat_participants', 'chat_messages', 'user_presence', 'chat_connections']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY tenant_isolation ON %I '
                       'USING (app_rls_bypass() OR tenant_id = app_current_tenant()) '
                       'WITH CHECK (app_rls_bypass() OR tenant_id = app_current_tenant())', t);
    END LOOP;
END
$$;
